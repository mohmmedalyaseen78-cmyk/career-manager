_DIAC = re.compile(r"[ً-ْـ]")
_ALEF = re.compile(r"[أإآٱ]")


def normalize(text):
    """Search normalisation: lowercase, strip Arabic diacritics/tatweel, unify alef/ya/ta-marbuta."""
    t = _DIAC.sub("", text.strip().lower())
    t = _ALEF.sub("ا", t)
    t = t.replace("ى", "ي").replace("ة", "ه")
    t = unicodedata.normalize("NFKD", t)
    return "".join(ch for ch in t if not unicodedata.combining(ch))


def pick_unique_name(rng, used):
    """Random 'first family' Arabic name not in `used` (set, updated in place)."""
    for _ in range(200):
        n = f"{rng.choice(FIRST)} {rng.choice(FAMILY)}"
        if n not in used:
            used.add(n)
            return n
    raise RuntimeError("name pool exhausted")
