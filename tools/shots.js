const {chromium}=require('playwright');const path=require('path');
(async()=>{const b=await chromium.launch();const p=await b.newPage({viewport:{width:1366,height:768},deviceScaleFactor:1});
const url='http://127.0.0.1:8765/index.html';const out=n=>path.resolve(__dirname,'../ui/screenshots/'+n+'.png');
const errs=[];p.on('pageerror',e=>errs.push(e.message));p.on('console',m=>m.type()==='error'&&errs.push(m.text()));
await p.goto(url);await p.waitForTimeout(300);await p.screenshot({path:out('01_start')});
await p.keyboard.press('Enter');await p.waitForTimeout(100);
await p.goto(url+'#central');await p.reload();await p.waitForTimeout(300);await p.screenshot({path:out('02_central')});
await p.keyboard.press('2');await p.waitForTimeout(200);await p.screenshot({path:out('03_squad')});
await p.click('#mb');await p.waitForTimeout(100);await p.screenshot({path:out('03b_squad_menu')});await p.keyboard.press('Escape');
await p.keyboard.press('3');await p.waitForTimeout(200);await p.screenshot({path:out('04_transfers')});
await p.click('#fb');await p.waitForTimeout(100);await p.screenshot({path:out('04b_transfers_filter')});
await p.goto(url+'?dev=1#states');await p.reload();await p.waitForTimeout(300);await p.screenshot({path:out('05_states')});
console.log('errors:',errs);await b.close()})();
